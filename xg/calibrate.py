"""Stage 2 of premistats xG: a Premier League calibration layer on top of the StatsBomb model.

The base model (xg/train.py) can't see defender or goalkeeper positions, so it
under-rates "big chances" and over-rates everything else (decision 021). WhoScored
tags big chances, so a small logistic regression learns the correction:

    final xG = sigmoid(a + b * logit(base xG) + c * big_chance + d * big_chance * logit(base xG))

It is fitted on one season (default 2025/26) and evaluated on a different one
(default 2026/27), so the test season is never used for fitting.

Usage:
    python -m xg.calibrate
    python -m xg.calibrate --fit-season 2526 --test-season 2627
"""
import argparse
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import duckdb
import joblib
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from sklearn.calibration import calibration_curve
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import brier_score_loss, log_loss, roc_auc_score

from analysis.branding import add_statsbomb_logo
from pipeline.config import DATA_DIR, ROOT
from xg.features import build_features

MODEL_DIR = DATA_DIR / "models"
SURFACE = "#fcfcfb"
INK, INK_2, INK_MUTED, GRID = "#0b0b0b", "#52514e", "#8a8984", "#e6e5e0"
BASE_COLOUR, CAL_COLOUR = "#eda100", "#2a78d6"
EPS = 1e-6


def logit(p):
    p = np.clip(p, EPS, 1 - EPS)
    return np.log(p / (1 - p))


def calibration_inputs(base_xg, big_chance) -> np.ndarray:
    z = logit(np.asarray(base_xg))
    b = np.asarray(big_chance, dtype=float)
    return np.column_stack([z, b, z * b])


def load_shots(season: str) -> pd.DataFrame:
    con = duckdb.connect(str(DATA_DIR / "warehouse.duckdb"), read_only=True)
    df = con.sql(f"""
        select s.* from silver.stg_shots s
        join silver.stg_matches m using (match_id)
        where m.season = '{season}' and s.situation <> 'penalty'
    """).df()
    con.close()
    if df.empty:
        sys.exit(f"No shots for season {season}. Run the pipeline for that season first.")
    return df


def base_xg(shots: pd.DataFrame, bundle: dict) -> np.ndarray:
    return bundle["model"].predict_proba(build_features(shots)[bundle["columns"]])[:, 1]


def score(y, p) -> dict:
    return {"log_loss": log_loss(y, p), "brier": brier_score_loss(y, p), "roc_auc": roc_auc_score(y, p),
            "sum_xg": float(np.sum(p)), "goals": int(np.sum(y))}


def by_kind(df: pd.DataFrame, col: str) -> pd.DataFrame:
    kind = np.where(df["is_big_chance"], "Big chances", "Other shots")
    return (df.assign(kind=kind).groupby("kind")
              .agg(shots=("is_goal", "size"), goals=("is_goal", "sum"), xg=(col, "sum")))


def plot(test: pd.DataFrame, season: str, out: Path) -> None:
    fig, ax = plt.subplots(figsize=(8, 7.4))
    fig.set_facecolor(SURFACE)
    ax.set_facecolor(SURFACE)
    fig.subplots_adjust(left=0.11, right=0.97, top=0.84, bottom=0.2)
    ax.plot([0, 1], [0, 1], color=GRID, lw=1.5, zorder=1)
    for col, colour, label in [("xg_base", BASE_COLOUR, "Base model (StatsBomb-trained)"),
                               ("xg", CAL_COLOUR, "Calibrated with big-chance flag")]:
        frac, mean_pred = calibration_curve(test["is_goal"], test[col], n_bins=10, strategy="quantile")
        ax.plot(mean_pred, frac, color=colour, lw=2, marker="o", ms=6, markeredgecolor=SURFACE,
                markeredgewidth=1.5, label=label, zorder=3)
    lim = 0.65
    ax.set_xlim(0, lim)
    ax.set_ylim(0, lim)
    ax.set_xlabel("Predicted xG", fontsize=12, color=INK_2)
    ax.set_ylabel("Actual goal rate", fontsize=12, color=INK_2)
    ax.tick_params(colors=INK_MUTED)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(GRID)
    fig.legend(loc="lower left", bbox_to_anchor=(0.1, 0.06), ncol=1, frameon=False, fontsize=10,
               labelcolor=INK_2)
    yr = f"20{season[:2]}/{season[2:]}"
    fig.text(0.11, 0.93, f"xG calibration, Premier League {yr}", fontsize=17, fontweight="bold", color=INK)
    fig.text(0.11, 0.89, "Test season only: never used to fit the calibration. 10 equal-size bins.",
             fontsize=10.5, color=INK_2)
    fig.text(0.97, 0.055, "premistats · data: WhoScored · model trained on", fontsize=8, color=INK_MUTED,
             ha="right")
    add_statsbomb_logo(fig, right=0.97, bottom=0.02, width=0.17)
    fig.savefig(out, dpi=150, facecolor=SURFACE)
    plt.close(fig)


def write_report(fit_season, test_season, n_fit, results, kinds, coefs, out: Path) -> None:
    yr = lambda s: f"20{s[:2]}/{s[2:]}"
    lines = [
        "# xG stage 2: Premier League calibration",
        "",
        f"*Generated by `python -m xg.calibrate` on {date.today():%d %b %Y}. Do not edit by hand.*",
        "",
        "The base model ([xg_model.md](xg_model.md)) can't see where defenders and the goalkeeper are, so "
        "it under-rates big chances and over-rates other shots (decision 021). Stage 2 corrects this with "
        "WhoScored's big-chance flag:",
        "",
        "`xG = sigmoid(a + b·logit(base xG) + c·big_chance + d·big_chance·logit(base xG))`",
        "",
        f"- **Fitted on:** Premier League {yr(fit_season)} ({n_fit:,} non-penalty shots)",
        f"- **Tested on:** Premier League {yr(test_season)}, a different season, never used for fitting",
        f"- **Coefficients:** a = {coefs[0]:.3f}, b = {coefs[1]:.3f}, c = {coefs[2]:.3f}, d = {coefs[3]:.3f}",
        "",
        f"## Results on {yr(test_season)} (non-penalty shots)",
        "",
        "| | Log loss | Brier | ROC AUC | Sum of xG | Goals |",
        "|---|---|---|---|---|---|",
        *[f"| {name} | {r['log_loss']:.4f} | {r['brier']:.4f} | {r['roc_auc']:.3f} | {r['sum_xg']:.1f} | {r['goals']} |"
          for name, r in results.items()],
        "",
        "### By shot type",
        "",
        "| | Shots | Goals | Base xG | Calibrated xG |",
        "|---|---|---|---|---|",
        *[f"| {k} | {int(r.shots):,} | {int(r.goals)} | {r.xg_base:.1f} | {r.xg:.1f} |" for k, r in kinds.iterrows()],
        "",
        "![Calibration by season](img/xg_stage2_calibration.png)",
        "",
        "Data: WhoScored (shots, big-chance flag). Base model trained on StatsBomb open data.",
        "",
        '<img src="img/statsbomb_logo.png" alt="StatsBomb" height="24">',
    ]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--fit-season", default="2526")
    parser.add_argument("--test-season", default="2627")
    args = parser.parse_args()

    bundle = joblib.load(MODEL_DIR / "xg_v1.joblib")
    fit, test = load_shots(args.fit_season), load_shots(args.test_season)
    fit["xg_base"], test["xg_base"] = base_xg(fit, bundle), base_xg(test, bundle)

    calibrator = LogisticRegression(C=1e6, max_iter=1000)  # effectively unregularised: only 3 inputs
    calibrator.fit(calibration_inputs(fit.xg_base, fit.is_big_chance), fit.is_goal.astype(int))
    test["xg"] = calibrator.predict_proba(calibration_inputs(test.xg_base, test.is_big_chance))[:, 1]

    y = test["is_goal"].astype(int)
    results = {"Base model": score(y, test.xg_base), "Calibrated (stage 2)": score(y, test.xg)}
    kinds = by_kind(test, "xg_base").rename(columns={"xg": "xg_base"}).join(by_kind(test, "xg")[["xg"]])
    coefs = [calibrator.intercept_[0], *calibrator.coef_[0]]
    print(pd.DataFrame(results).T.round(4).to_string())
    print(kinds.round(1).to_string())

    joblib.dump({"calibrator": calibrator, "fit_season": args.fit_season, "date": date.today().isoformat()},
                MODEL_DIR / "xg_v2_calibration.joblib")
    plot(test, args.test_season, ROOT / "docs" / "img" / "xg_stage2_calibration.png")
    write_report(args.fit_season, args.test_season, len(fit), results, kinds, coefs,
                 ROOT / "docs" / "xg_calibration.md")
    print("Saved calibrator, docs/xg_calibration.md and chart")


if __name__ == "__main__":
    main()
